<?php

declare(strict_types=1);

namespace App\Modules\Numbering\Services;

use App\Modules\Numbering\Models\NumberingCounter;
use Illuminate\Support\Facades\DB;
use RuntimeException;

/**
 * ALLOW_GAPS. Each counter owns a PostgreSQL sequence. `nextval` is not transactional: it never waits on another issue, and a
 * value taken by a transaction that later rolls back (or by a crash) is not returned — a gap. Numbers still only rise and are
 * never repeated. PostgreSQL's own documentation is explicit that sequences cannot provide gapless numbering; that is the
 * LOCKED strategy's job.
 */
final class SequenceCounterStrategy implements AllocationStrategy
{
    public function allocate(NumberingCounter $counter): int
    {
        return (int) DB::selectOne("select nextval('".$this->name($counter)."') as value")->value;
    }

    public function peek(NumberingCounter $counter): int
    {
        $row = DB::selectOne('select last_value, is_called from '.$this->name($counter));

        return (int) $row->last_value + ($row->is_called ? 1 : 0);
    }

    public function raiseTo(NumberingCounter $counter, int $next): void
    {
        // setval(seq, n, true) makes the next nextval n + 1; to make it $next, set to $next - 1 as "called" (or 1 as "not called").
        $name = $this->name($counter);
        if ($next <= 1) {
            DB::select("select setval('{$name}', 1, false)");
        } else {
            DB::select("select setval('{$name}', ?, true)", [$next - 1]);
        }
    }

    /** Creates the sequence for a new counter, starting at $start. The name is generated by us, never user input. */
    public function create(string $name, int $start = 1): void
    {
        $this->assertSafe($name);
        DB::statement("create sequence {$name} start with {$start} minvalue 1");
    }

    public function drop(string $name): void
    {
        $this->assertSafe($name);
        DB::statement("drop sequence if exists {$name}");
    }

    private function name(NumberingCounter $counter): string
    {
        $name = (string) $counter->sequence_name;
        $this->assertSafe($name);

        return $name;
    }

    private function assertSafe(string $name): void
    {
        if (! preg_match('/^numbering_seq_[a-f0-9]{12}$/', $name)) {
            throw new RuntimeException('Unsafe sequence name.');
        }
    }
}
