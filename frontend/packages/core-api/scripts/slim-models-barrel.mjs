// Runs after every `orval` generation (see `hooks.afterAllFilesWrite` in orval.config.ts).
//
// Orval writes `src/generated/models/index.ts` as one `export * from "./x"` line per generated
// schema — over a thousand of them. `export *` is a value re-export a browser cannot skip, so in
// dev (where Vite serves each file as its own module) every cold page load fetched every one of
// those files, although the overwhelming majority are pure TypeScript types that compile to empty
// modules. That was ~1,500 requests and file reads per cold load, and made the dev app crawl
// whenever the disk was busy.
//
// The barrel is rewritten so a file with no runtime export (interface / type alias only) is
// re-exported with `export type *`, which is erased at build time and requested by nobody; only
// files that export something that runs (an enum-like `export const X = {...} as const`) keep the
// value re-export. The set of names visible from `@erp/core-api` is unchanged.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const modelsDir = new URL('../src/generated/models/', import.meta.url);
const runtimeExport = /^export\s+(const|let|var|function|class|enum)\b/m;

const files = readdirSync(modelsDir)
  .filter((file) => file.endsWith('.ts') && file !== 'index.ts')
  .sort();

let runtime = 0;
const lines = files.map((file) => {
  const module = `./${file.slice(0, -'.ts'.length)}`;
  if (runtimeExport.test(readFileSync(new URL(file, modelsDir), 'utf8'))) {
    runtime += 1;
    return `export * from "${module}";`;
  }

  return `export type * from "${module}";`;
});

const header = `/**
 * Generated by orval, then rewritten by scripts/slim-models-barrel.mjs.
 * Do not edit manually.
 *
 * Pure-type schemas are re-exported with \`export type *\` so a browser never requests them;
 * only the ${runtime} schemas that export a runtime value use \`export *\`.
 */
`;

writeFileSync(new URL('index.ts', modelsDir), `${header}${lines.join('\n')}\n`);
console.log(`models barrel: ${files.length} schemas, ${runtime} runtime, ${files.length - runtime} type-only`);
